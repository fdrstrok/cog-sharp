package plugin

import (
	"bytes"
	"fmt"
	"log/slog"

	"github.com/fdrstrok/cog-sharp/internal/csharp"
	"github.com/goccy/go-yaml"
	"github.com/grafana/codejen"
	"github.com/grafana/cog/pkg/ir"
	"github.com/grafana/cog/pkg/jennies"
	"github.com/grafana/cog/pkg/languages"
	"github.com/grafana/cog/pkg/plugins"
)

var _ plugins.Language = (*Language)(nil)

type Language struct {
	logger *slog.Logger
}

func New(logger *slog.Logger) *Language {
	if logger == nil {
		logger = plugins.DefaultLogger
	}
	return &Language{logger: logger}
}

func (l *Language) ValidateConfig(input map[string]any) error {
	config, err := readConfig(input)
	if err != nil {
		return err
	}
	if config.GenerateEquality {
		return fmt.Errorf("generate_equality is not implemented")
	}
	if config.SkipRuntime && config.GenerateJSONConverters {
		return fmt.Errorf("skip_runtime cannot be used with generate_json_converters")
	}
	if len(config.ExtraFilesTemplatesDirectories) != 0 {
		return fmt.Errorf("extra_files_templates is not implemented")
	}
	return nil
}

func (l *Language) NullableConfig(_ map[string]any) (languages.NullableConfig, error) {
	return csharp.New(csharp.Config{}).NullableKinds(), nil
}

func (l *Language) TransformSchemas(_ map[string]any, schemas ir.Schemas) (ir.Schemas, error) {
	return csharp.New(csharp.Config{}).CompilerPasses().Process(l.logger, schemas)
}

func (l *Language) Generate(global languages.Config, input map[string]any, context languages.Context) (codejen.Files, error) {
	if err := l.ValidateConfig(input); err != nil {
		return nil, err
	}
	config, err := readConfig(input)
	if err != nil {
		return nil, err
	}
	if config.SkipRuntime && global.Builders {
		return nil, fmt.Errorf("skip_runtime cannot be used with builders")
	}
	if global.Converters {
		return nil, fmt.Errorf("option converters are not implemented; set output.converters to false")
	}
	if global.APIReference {
		return nil, fmt.Errorf("API reference generation is not implemented; set output.api_reference to false")
	}

	files, err := csharp.New(config).Jennies(global).Generate(context)
	if err != nil {
		return nil, err
	}
	for i, file := range files {
		data := append([]byte("// Code generated by cog-sharp. DO NOT EDIT.\n\n"), file.Data...)
		files[i] = *jennies.NewFile(file.RelativePath, data)
	}
	return files, nil
}

func readConfig(input map[string]any) (csharp.Config, error) {
	config := csharp.Config{}
	payload, err := yaml.Marshal(input)
	if err != nil {
		return config, err
	}
	if err := yaml.NewDecoder(bytes.NewReader(payload), yaml.DisallowUnknownField()).Decode(&config); err != nil {
		return config, err
	}
	config.InterpolateParameters(func(value string) string { return value })
	return config, nil
}
